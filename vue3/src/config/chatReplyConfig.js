export function matchFixedAnswer(message) {
  const msg = String(message || '').trim().toLowerCase()
  if (!msg) return null

  for (const rule of FIXED_REPLY_RULES) {
    if (rule.patterns.some((pattern) => pattern.test(msg))) {
      return rule.reply
    }
  }

  return null
}
